/** 把档案内容合并进纹样列表（不改动基础字段） */
export function withArchive<T extends { id: string }>(patterns: T[]): T[] {
  return patterns.map((p) => {
    const extra = PATTERN_ARCHIVE[p.id];
    return extra ? { ...p, ...extra } : p;
  });
}
